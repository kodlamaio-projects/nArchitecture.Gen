using System.Text;

namespace Application.Features.Upgrade;

public enum ManualWorkKind
{
    Mediator,
    AutoMapper,
    Tests,
    WebApi,
    ProjectFiles,
}

public sealed record ManualWorkItem(ManualWorkKind Kind, string FilePath, int Line, string Reason);

public sealed record AppliedChange(string Step, string Description);

/// <summary>Collects what the upgrade did, skipped and could not do; rendered to MIGRATION-REPORT.md.</summary>
public sealed class UpgradeReport
{
    private const string _guideUrl = "https://github.com/kodlamaio-projects/nArchitecture.Core/blob/main/docs/migration-guide-2.0.md";

    public List<AppliedChange> Applied { get; } = [];
    public List<string> SkippedSteps { get; } = [];
    public List<ManualWorkItem> ManualWork { get; } = [];
    public Dictionary<string, string> Analysis { get; } = [];
    public string? BuildSummary { get; set; }
    public bool DryRun { get; set; }

    public void Add(string step, string description) => Applied.Add(new AppliedChange(step, description));

    public void Manual(ManualWorkKind kind, string filePath, int line, string reason) =>
        ManualWork.Add(new ManualWorkItem(kind, filePath, line, reason));

    public string Render(string solutionPath)
    {
        StringBuilder sb = new();
        sb.AppendLine("# nArchitecture 2.0 upgrade report");
        sb.AppendLine();
        sb.AppendLine(
            $"Generated by `nArchGen upgrade` on {DateTime.Now:yyyy-MM-dd HH:mm}.{(DryRun ? " **Dry run: no files were changed.**" : string.Empty)}"
        );
        sb.AppendLine();
        sb.AppendLine($"Guide: {_guideUrl}");
        sb.AppendLine();

        sb.AppendLine("## Analysis");
        sb.AppendLine();
        sb.AppendLine("| Item | Value |");
        sb.AppendLine("|---|---|");
        foreach ((string key, string value) in Analysis)
            sb.AppendLine($"| {key} | {value} |");
        sb.AppendLine();

        sb.AppendLine("## Applied changes");
        sb.AppendLine();
        if (Applied.Count == 0)
            sb.AppendLine("_None._");
        foreach (IGrouping<string, AppliedChange> group in Applied.GroupBy(a => a.Step))
        {
            sb.AppendLine($"### {group.Key}");
            foreach (AppliedChange change in group)
                sb.AppendLine($"- {change.Description}");
            sb.AppendLine();
        }

        if (SkippedSteps.Count > 0)
        {
            sb.AppendLine("## Skipped steps");
            sb.AppendLine();
            foreach (string step in SkippedSteps)
                sb.AppendLine($"- {step}");
            sb.AppendLine();
        }

        sb.AppendLine("## Manual work");
        sb.AppendLine();
        if (ManualWork.Count == 0)
            sb.AppendLine("_Nothing left to do by hand._");
        else
        {
            sb.AppendLine("| Area | Location | What to do |");
            sb.AppendLine("|---|---|---|");
            foreach (ManualWorkItem item in ManualWork.OrderBy(m => m.Kind).ThenBy(m => m.FilePath).ThenBy(m => m.Line))
            {
                string location = Path.GetRelativePath(solutionPath, item.FilePath).Replace('\\', '/');
                if (item.Line > 0)
                    location += $":{item.Line}";
                sb.AppendLine($"| {item.Kind} | `{location}` | {item.Reason} ({guideAnchor(item.Kind)}) |");
            }
        }
        sb.AppendLine();

        if (BuildSummary is not null)
        {
            sb.AppendLine("## Build");
            sb.AppendLine();
            sb.AppendLine(BuildSummary);
        }

        return sb.ToString();
    }

    private static string guideAnchor(ManualWorkKind kind) =>
        kind switch
        {
            ManualWorkKind.Mediator => $"{_guideUrl}#step-2--mediator",
            ManualWorkKind.AutoMapper => $"{_guideUrl}#step-3--automapper--mapperly",
            ManualWorkKind.Tests => $"{_guideUrl}#step-5--test-project",
            ManualWorkKind.WebApi => $"{_guideUrl}#step-4--core-breaking-changes",
            _ => $"{_guideUrl}#step-1--project-files",
        };
}
